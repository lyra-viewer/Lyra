    public static string? Name(TiffDirectoryKind kind, ushort tag)
    {
        if (kind == TiffDirectoryKind.Gps && GpsNames.TryGetValue(tag, out var gps))
            return gps;

        if (BaseNames.TryGetValue(tag, out var name))
            return name;

        return kind is TiffDirectoryKind.Image or TiffDirectoryKind.SubImage && DngNames.TryGetValue(tag, out var dng) ? dng : null;
    }

    /// <summary>The name of a tag in an RW2's IFD0, where Panasonic keeps its own tags, some on numbers TIFF uses for others.</summary>
    public static string? PanasonicRawName(ushort tag) => PanasonicRawNames.GetValueOrDefault(tag);

